    class automatico extends Thread {

        @Override
        public void run() {

            int i = Ingredientes.getSize();
            int j = Platillo.getSize();

            if (i > j) {
                for (int x = 0; x < i; x++) {
                    Platillo.addElement(Ingredientes.getElementAt(0));
                    Ingredientes.removeElementAt(0);
                    try {
                        Thread.sleep(500);
                    } catch (InterruptedException ex) {
                        System.getLogger(RestauranteMiguel.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
                    }

                }
            }else{
                for (int x = 0; x < j; x++) {
                    Ingredientes.addElement(Platillo.getElementAt(0));
                    Platillo.removeElementAt(0);
                    try {
                        Thread.sleep(500);
                    } catch (InterruptedException ex) {
                        System.getLogger(RestauranteMiguel.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
                    }

                }
            }

        }
    }
    
    class reloj extends Thread {

        @Override
        public void run() {
            while (true) {
                Date fecha = new Date();
                String formato = "hh:mm:ss";
                String formato2 = "dd-MM-yyyy";
                SimpleDateFormat ff = new SimpleDateFormat(formato2);
                SimpleDateFormat fh = new SimpleDateFormat(formato);
                jLabel7.setText(ff.format(fecha));
                jLabel8.setText(fh.format(fecha));
                try {
                    Thread.sleep(1000);
                } catch (InterruptedException ex) {
                    System.getLogger(RegistroAlumnos.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
                }
            }
        }
    }
