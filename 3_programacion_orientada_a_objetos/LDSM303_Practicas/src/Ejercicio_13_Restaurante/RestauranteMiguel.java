    private void btnordenarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnordenarMouseClicked

        int i = Ingredientes.getSize();

        datos = new String[i];

        for (int j = 0; j < i; j++) {
            //Platillo.addElement(Ingredientes.getElementAt(j));
            datos[j] = Ingredientes.getElementAt(j).toString();
        }
        Ingredientes.removeAllElements();
        Arrays.sort(datos);//para ordenr arreglos de caulquier tipo
        
        for (int j = 0; j < i; j++) {
            
            Ingredientes.addElement(datos[j]);
           
        }


    }//GEN-LAST:event_btnordenarMouseClicked

