    public void Buscar(String id) throws SQLException{
        String sql = "Select * from empleados where id_empleado= '" + id + "'";
        t = cm.getConnection().createStatement(ResultSet.TYPE_SCROLL_SENSITIVE, ResultSet.CONCUR_UPDATABLE);
        r = t.executeQuery(sql);
        r.first();
        this.jTextField1.setText(r.getString(1));
        this.jTextField2.setText(r.getString(2));
        this.jTextField3.setText(r.getString(3));
        this.jTextField4.setText(r.getString(4));
        this.jTextField5.setText(r.getString(5));
 
    }
    
     public void InsertarE(){
        String id_empleado, nombre;
        float sueldo;
        int edad, antiguedad;
        id_empleado=jTextField1.getText();
        nombre = jTextField2.getText();
        edad= Integer.parseInt(this.jTextField3.getText());
        sueldo = Float.parseFloat(this.jTextField4.getText());
        antiguedad= Integer.parseInt(this.jTextField5.getText());
        e = new Empleado(id_empleado, nombre, edad,sueldo,antiguedad);
    }
     
    public void InsertarEnBase(Empleado e) throws SQLException{
        String sql ="Insert into empleados(id_empleado, nombre, edad, sueldo, antiguedad)" 
        + " values ('" + e.getId_empleado() + "','"
        + e.getNombre() + "',"
        + e.getEdad() + ", "
        + e.getSueldo() + ", "
        + e.getAntiguedad() + ")";
       
        t=cm.getConnection().createStatement(ResultSet.TYPE_SCROLL_SENSITIVE, ResultSet.CONCUR_UPDATABLE);
        t.executeUpdate(sql);
       
    }
    
