    private void btninsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btninsertarActionPerformed
        try {
            String id_empleado = jTextField1.getText();
            String nombre = jTextField2.getText();
            String edad = jTextField3.getText();
            String sueldo = jTextField4.getText();
            String antiguedad = jTextField5.getText();
            
            if (id_empleado.isEmpty()|| nombre.isEmpty()|| edad.isEmpty()|| sueldo.isEmpty()|| antiguedad.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Checa los datos");
            }else{
            InsertarE();
            InsertarEnBase(e);
            JOptionPane.showMessageDialog(this,"Empleado insertado correctamente");
            jTextField1.setText(null);
            jTextField2.setText(null);
            jTextField3.setText(null);
            jTextField4.setText(null);
            jTextField5.setText(null);
            }
           
            
            
           
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error en ingresar datos");
            
        }
    }//GEN-LAST:event_btninsertarActionPerformed

    private void btnbuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnbuscarActionPerformed
        try {
            String id = jTextField1.getText();
            
            if (id.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Escribe un id");
                return;
            }
            
            Buscar(id);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error al buscar al empleado");
        }
    }//GEN-LAST:event_btnbuscarActionPerformed

